const getWeekDates = (offsetWeeks = 0) => {
  const now = new Date();
  const currentDay = now.getDay();
  const diffToMonday = now.getDate() - currentDay + (currentDay === 0 ? -6 : 1) + (offsetWeeks * 7);
  const monday = new Date(now.getFullYear(), now.getMonth(), diffToMonday);

  const dayNames = ['Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado', 'Domingo'];
  const dayKeys = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];

  return dayKeys.map((key, index) => {
    const dayDate = new Date(monday.getFullYear(), monday.getMonth(), monday.getDate() + index);
    const dateStr = dayDate.toLocaleDateString('es-ES', { day: 'numeric', month: 'short' });
    const fullDate = dayDate.toISOString().split('T')[0];
    return { key, name: dayNames[index], dateStr, fullDate };
  });
};

